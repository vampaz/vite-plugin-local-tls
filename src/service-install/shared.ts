export async function assertOwnedDefinition(
  definitionPath: string,
  expectation?:
    | { options: ServiceInstallOptions; record: ServiceInstallationRecord }
    | Array<{ options: ServiceInstallOptions; record: ServiceInstallationRecord }>,
  requireExisting = false,
): Promise<void> {
  try {
    const details = await lstat(definitionPath);
    if (!details.isFile() || details.isSymbolicLink()) {
      throw new Error(`Refusing unsafe service definition: ${definitionPath}`);
    }
    const contents = await readFile(definitionPath, 'utf8');
    const expectations = Array.isArray(expectation)
      ? expectation
      : expectation
        ? [expectation]
        : [];
    if (
      expectations.length === 0 ||
      !expectations.some(({ options, record }) =>
        serviceDefinitionMatchesInstallation(contents, options, record),
      )
    ) {
      throw new Error(`Refusing to overwrite unrelated service definition: ${definitionPath}`);
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT' && requireExisting) {
      throw new Error(`The recorded startup service definition is missing: ${definitionPath}`);
    }
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      throw error;
    }
  }
}

export function launchdDefinition(
  options: ServiceInstallOptions,
  identifier: string,
  recordVersion: 1 | 2 = 2,
): string {
  const user = os.userInfo();
  const username = options.username ?? user.username;
  const uid = options.uid ?? user.uid;
  const gid = options.gid ?? user.gid;
  const arguments_ = [
    options.nodePath,
    options.cliPath,
    'proxy',
    'start',
    '--service',
    '--namespace',
    options.namespace,
    '--run-as-uid',
    String(uid),
    '--run-as-gid',
    String(gid),
  ];
  if (options.controlSocket) {
    arguments_.push('--control-socket', options.controlSocket);
  }
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    `  <!-- ${recordVersion === 1 ? LEGACY_STARTUP_SERVICE_OWNER_MARKER : OWNER_MARKER} -->`,
    '  <key>Label</key>',
    `  <string>${xmlEscape(identifier)}</string>`,
    '  <key>ProgramArguments</key>',
    '  <array>',
    ...arguments_.map((argument) => `    <string>${xmlEscape(argument)}</string>`),
    '  </array>',
    '  <key>EnvironmentVariables</key>',
    '  <dict>',
    '    <key>HOME</key>',
    `    <string>${xmlEscape(options.homeDirectory ?? os.homedir())}</string>`,
    '    <key>USER</key>',
    `    <string>${xmlEscape(username)}</string>`,
    '    <key>LOGNAME</key>',
    `    <string>${xmlEscape(username)}</string>`,
    '    <key>VITE_LOCAL_TLS_USER_ID</key>',
    `    <string>${uid}</string>`,
    '    <key>VITE_LOCAL_TLS_RUNTIME_DIRECTORY</key>',
    `    <string>${xmlEscape(options.paths.runtimeDirectory)}</string>`,
    '  </dict>',
    '  <key>RunAtLoad</key>',
    '  <true/>',
    '  <key>KeepAlive</key>',
    ...(recordVersion === 1
      ? ['  <true/>']
      : ['  <dict>', '    <key>SuccessfulExit</key>', '    <false/>', '  </dict>']),
    '  <key>ProcessType</key>',
    '  <string>Background</string>',
    '  <key>StandardOutPath</key>',
    `  <string>${xmlEscape(path.join(options.paths.stateDirectory, 'service.log'))}</string>`,
    '  <key>StandardErrorPath</key>',
    `  <string>${xmlEscape(path.join(options.paths.stateDirectory, 'service-error.log'))}</string>`,
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

export async function installUserRuntime(
  options: ServiceInstallOptions,
  key: string,
): Promise<{ nodePath: string; cliPath: string; runtimeDirectory: string }> {
  const runtimeDirectory =
    options.runtimeInstallDirectory ??
    expectedRuntimeDirectory(
      options,
      options.platform ?? process.platform,
      safeServiceKey(options),
    );
  const nodePath = path.join(
    runtimeDirectory,
    (options.platform ?? process.platform) === 'win32' ? 'n.exe' : 'node',
  );
  const cliPath = path.join(
    runtimeDirectory,
    (options.platform ?? process.platform) === 'win32' ? 'c.js' : `cli-${key}.js`,
  );
  await mkdir(runtimeDirectory, { recursive: true, mode: 0o700 });
  await Promise.all([
    replaceRuntimeFile(options.nodePath, nodePath, options.platform ?? process.platform),
    replaceRuntimeFile(options.cliPath, cliPath, options.platform ?? process.platform),
  ]);
  return { nodePath, cliPath, runtimeDirectory };
}

export async function replaceRuntimeFile(
  sourcePath: string,
  destinationPath: string,
  platform: NodeJS.Platform,
): Promise<void> {
  const temporaryPath = `${destinationPath}.${process.pid}.${randomUUID()}.tmp`;
  await copyFile(sourcePath, temporaryPath);
  try {
    if (platform !== 'win32') {
      await chmod(temporaryPath, 0o700);
      await rename(temporaryPath, destinationPath);
      return;
    }
    let lastError: unknown;
    for (let attempt = 0; attempt < 20; attempt += 1) {
      try {
        await copyFile(temporaryPath, destinationPath);
        return;
      } catch (error) {
        lastError = error;
        const code = (error as NodeJS.ErrnoException).code;
        if (!['EBUSY', 'EACCES', 'EPERM'].includes(code ?? '') || attempt === 19) {
          throw error;
        }
        await new Promise((resolve) => setTimeout(resolve, 50));
      }
    }
    throw lastError;
  } finally {
    await unlink(temporaryPath).catch(() => undefined);
  }
}

export async function stageRegularFileBackup(
  sourcePath: string,
  backupPath: string,
): Promise<void> {
  const details = await lstat(sourcePath);
  if (!details.isFile() || details.isSymbolicLink()) {
    throw new Error(`Refusing unsafe installed service runtime: ${sourcePath}`);
  }
  try {
    const backupDetails = await lstat(backupPath);
    if (!backupDetails.isFile() || backupDetails.isSymbolicLink()) {
      throw new Error(`Refusing unsafe installed service backup: ${backupPath}`);
    }
    return;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      throw error;
    }
  }
  const temporaryPath = `${backupPath}.${process.pid}.${randomUUID()}.tmp`;
  try {
    await copyFile(sourcePath, temporaryPath);
    await rename(temporaryPath, backupPath);
  } finally {
    await unlink(temporaryPath).catch(() => undefined);
  }
}

export function serviceBackupKey(
  options: ServiceInstallOptions,
  record: ServiceInstallationRecord,
): string {
  const fingerprint = createHash('sha256')
    .update(JSON.stringify(record))
    .digest('hex')
    .slice(0, 12);
  return `${safeServiceKey(options)}-${fingerprint}`;
}

export function systemdDefinition(
  options: ServiceInstallOptions,
  recordVersion: 1 | 2 = 2,
): string {
  const username = options.username ?? os.userInfo().username;
  const runtimeUnit = recordVersion === 2 ? linuxUserRuntimeUnit(options) : null;
  const arguments_ = [
    options.nodePath,
    options.cliPath,
    'proxy',
    'start',
    '--service',
    '--namespace',
    options.namespace,
  ];
  if (options.controlSocket) {
    arguments_.push('--control-socket', options.controlSocket);
  }
  return [
    `# ${recordVersion === 1 ? LEGACY_STARTUP_SERVICE_OWNER_MARKER : OWNER_MARKER}`,
    '[Unit]',
    'Description=Vite local TLS proxy',
    `After=network.target${runtimeUnit ? ` ${runtimeUnit}` : ''}`,
    ...(runtimeUnit ? [`Requires=${runtimeUnit}`] : []),
    '',
    '[Service]',
    'Type=simple',
    `User=${username}`,
    `Environment=HOME=${systemdQuote(options.homeDirectory ?? os.homedir())}`,
    `Environment=VITE_LOCAL_TLS_RUNTIME_DIRECTORY=${systemdQuote(options.paths.runtimeDirectory)}`,
    `ExecStart=${arguments_.map(systemdQuote).join(' ')}`,
    'Restart=on-failure',
    'RestartSec=1',
    'AmbientCapabilities=CAP_NET_BIND_SERVICE',
    'CapabilityBoundingSet=CAP_NET_BIND_SERVICE',
    'NoNewPrivileges=true',
    'PrivateTmp=false',
    '',
    '[Install]',
    'WantedBy=multi-user.target',
    '',
  ].join('\n');
}

export function usesSudo(options: ServiceInstallOptions): boolean {
  return options.useSudo === true || (options.useSudo !== false && process.getuid?.() !== 0);
}

export function runElevatedCommand(
  options: ServiceInstallOptions,
  runner: ServiceInstallCommandRunner,
  command: string,
  arguments_: string[],
  timeoutMs?: number,
): Promise<ServiceInstallCommandResult> {
  const useSudo = usesSudo(options);
  if (!useSudo) {
    return timeoutMs ? runner(command, arguments_, { timeoutMs }) : runner(command, arguments_);
  }
  return runner('sudo', ['--', command, ...arguments_], {
    interactive: true,
    ...(timeoutMs ? { timeoutMs } : {}),
  });
}

export async function runElevatedCommands(
  options: ServiceInstallOptions,
  runner: ServiceInstallCommandRunner,
  commands: ServiceInstallElevatedCommand[],
): Promise<void> {
  if ((options.platform ?? process.platform) === 'darwin' && usesSudo(options) && !process.env.CI) {
    await runner('/usr/bin/osascript', [
      '-e',
      'on run argv',
      '-e',
      'set commandPath to quoted form of (item 1 of argv)',
      '-e',
      'set source to quoted form of (item 2 of argv)',
      '-e',
      'set requests to quoted form of (item 3 of argv)',
      '-e',
      'do shell script (commandPath & " --input-type=module --eval " & source & " " & requests) with administrator privileges with prompt "Vite Local TLS needs permission to install or update its local HTTPS service."',
      '-e',
      'end run',
      process.execPath,
      MACOS_ELEVATED_SEQUENCE_SOURCE,
      JSON.stringify(commands),
    ]);
    return;
  }
  const rollback: ServiceInstallElevatedCommand[][] = [];
  for (const request of commands) {
    try {
      await runElevatedCommand(
        options,
        runner,
        request.command,
        request.arguments_,
        request.timeoutMs,
      );
      if (request.clearRollbackAfterSuccess) {
        rollback.length = 0;
      }
      if (request.discardRollbackAfterSuccess) {
        rollback.pop();
      }
      if (request.rollbackAfterSuccess?.length) {
        rollback.push(request.rollbackAfterSuccess);
      }
    } catch (error) {
      if (!request.allowFailure) {
        let rollbackFailed = false;
        for (const group of [...rollback].reverse()) {
          for (const recovery of group) {
            try {
              await runElevatedCommand(
                options,
                runner,
                recovery.command,
                recovery.arguments_,
                recovery.timeoutMs,
              );
            } catch {
              if (!recovery.allowFailure) {
                rollbackFailed = true;
                break;
              }
            }
          }
          if (rollbackFailed) {
            break;
          }
        }
        throw error;
      }
    }
  }
}

export async function inspectRunningInstallations(
  installations: ObsoleteServiceInstallation[],
): Promise<ObsoleteServiceInstallation[]> {
  return Promise.all(
    installations.map(async (item) => ({
      ...item,
      wasRunning: (await installedService(item.installation).status()).running,
    })),
  );
}
