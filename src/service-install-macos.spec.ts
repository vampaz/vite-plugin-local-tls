function compileAppleScript(arguments_: string[], outputPath: string): Promise<void> {
  return new Promise((resolve, reject) => {
    execFile('/usr/bin/osacompile', ['-o', outputPath, ...arguments_], (error) => {
      if (error) {
        reject(error);
        return;
      }
      resolve();
    });
  });
}

